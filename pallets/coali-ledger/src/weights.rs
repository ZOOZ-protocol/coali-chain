/// `W` with its execution time multiplied by `N`: the benchmarks above were measured on a
/// development machine (Apple M-series), faster than the validator servers, so the runtime
/// charges `Margin<SubstrateWeight<_>, 3>` until they are re-run on reference hardware.
/// Database reads, writes and proof sizes are kept as measured.
pub struct Margin<W, const N: u64>(PhantomData<W>);

macro_rules! scaled {
	($($name:ident($($arg:ident: $ty:ty),*)),* $(,)?) => {
		impl<W: WeightInfo, const N: u64> WeightInfo for Margin<W, N> {
			$(fn $name($($arg: $ty),*) -> Weight {
				let w = W::$name($($arg),*);
				Weight::from_parts(w.ref_time().saturating_mul(N), w.proof_size())
			})*
		}
	};
}

